/**
 * AI Loading Overlay.
 * Displays a centered spinner with messaging while AI generates content.
 * Shows a green success banner at the top when AI has just finished.
 *
 * Stuck-state recovery: after 270 s the overlay calls clearAiWorking() to
 * unblock the step in case the server-side generation crashed without
 * clearing current_blocks_updating.
 */
"use client";

import { useState, useEffect } from "react";
import { toast } from "sonner";
import { cn } from "@/lib/utils";
import type { IdeaBlock } from "@/types/idea-refiner";
import { IDEA_BLOCK_LABELS } from "@/types/idea-refiner";
import { clearAiWorking } from "../actions";

/** Default stuck timeout for single-shot steps (≤4 AI calls). */
const STUCK_TIMEOUT_MS = 270_000;
/** strategic_frameworks loops one AI call per ICP — allow 10 min for up to ~10 ICPs. */
const STRATEGIC_FRAMEWORKS_STUCK_TIMEOUT_MS = 600_000;
/**
 * The Risk & Validation step runs the multi-call Devil's Advocate debate pipeline.
 * With the round cap at 10 per gate (MAX_ROUNDS_PER_GATE), a fully-contested idea
 * can reach ~40 debate calls (10 rounds × 2 sides × 2 gates) plus the risk/validation
 * + demand-evidence synthesis call. The debate is the crux kill/refine/build gate,
 * so we never want the stuck-state auto-clear to fire while a valid generation is
 * still running — 45 min covers the worst case even on slower models. Report (which
 * now only reframes + scores using the debate outcome) keeps the same ceiling for
 * safety. Latency is intentionally traded for verdict quality.
 */
const DEBATE_STUCK_TIMEOUT_MS = 2_700_000;

/** Field names that AI updates per step — shown in the "soon you will have…" message. */
const STEP_FIELDS: Record<IdeaBlock, string[]> = {
  ideas: [],
  structure_align: ["The Core Problem", "Target Audience", "Primary Success Metrics"],
  refining_icp: [
    "Day in the Life",
    "Pain Points & Acute Needs",
    "How problems are solved today",
    "How problems could be solved",
    "Our Solution Value",
  ],
  product_definition_flows: ["Product Summary", "Feature List & Logic", "Go-to-Market"],
  location_legislation: ["Regulatory Bodies", "Key Legislation", "Licensing Requirements", "Data Privacy Rules", "Compliance Timeline", "Regulatory Moat", "Red Flags"],
  market_opportunity: ["TAM", "SAM", "SOM", "Price Point", "Billing Model", "CAC", "LTV", "Growth Drivers", "Market Risks"],
  strategic_frameworks: [
    "Value Proposition",
    "JTBD Synthesis",
    "ICP Architect",
    "NABC Pitch",
    "Optimization Suggestions",
  ],
  benchmarking: ["Overview", "Comparison Table", "Possible Business Models", "Key Takeaways"],
  prd: [
    "App Overview",
    "Objectives",
    "Users Type",
    "Essential Features",
    "User Flow",
    "Non-Functional Reqs",
    "Out of Scope",
    "Success Indicators",
    "Phasing Notes",
  ],
  database: ["Tables & Schema", "Relationships", "Important Notes"],
  visual_styles: ["Brand Identity", "Color System", "Typography", "Spacing & Shadows", "Motion & Iconography"],
  milestones_and_tasks: ["Milestones & Tasks"],
  report: [
    "Devil's Advocate Debate",
    "Agreed Problem & Solution",
    "Alignment Score",
    "Revised Idea Description",
    "Go/No-Go Verdict",
  ],
  risk_and_validation: ["Risk Register", "Validation Experiment", "Why We Win"],
  playbook: ["Playbook Content"],
};

interface AiLoadingOverlayProps {
  /** The idea being processed — used to clear a stuck state. */
  ideaId: string;
  /** The step currently being generated by AI. */
  step: IdeaBlock;
  /** Whether the AI has just completed (show success banner). */
  justCompleted?: boolean;
}

/** Full-area overlay shown while AI is generating content for a step. */
export default function AiLoadingOverlay({
  ideaId,
  step,
  justCompleted = false,
}: AiLoadingOverlayProps) {
  const [showSuccess, setShowSuccess] = useState(justCompleted);
  const [isStuck, setIsStuck] = useState(false);
  const [isClearing, setIsClearing] = useState(false);

  // Auto-dismiss success banner after 5 seconds
  useEffect(() => {
    if (!showSuccess) return;
    const timer = setTimeout(() => setShowSuccess(false), 5000);
    return () => clearTimeout(timer);
  }, [showSuccess]);

  // Show success banner when justCompleted changes to true
  useEffect(() => {
    if (justCompleted) setShowSuccess(true);
  }, [justCompleted]);

  // Stuck-state detector: if the overlay has been showing too long without
  // resolving, the server-side generation probably crashed. Clear the flag so
  // the step becomes interactive again. The report step uses a longer timeout
  // because it runs a multi-call debate pipeline (~12-20 AI calls).
  useEffect(() => {
    if (justCompleted) return; // already done — don't arm the timer
    const timeoutMs =
      step === "risk_and_validation" || step === "report" ? DEBATE_STUCK_TIMEOUT_MS :
      step === "strategic_frameworks" ? STRATEGIC_FRAMEWORKS_STUCK_TIMEOUT_MS :
      STUCK_TIMEOUT_MS;
    const timer = setTimeout(async () => {
      setIsStuck(true);
      toast.error(
        `AI generation for ${IDEA_BLOCK_LABELS[step]} did not complete. The step has been unblocked — try regenerating.`,
        { duration: 10_000 }
      );
      await clearAiWorking(ideaId);
    }, timeoutMs);
    return () => clearTimeout(timer);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [ideaId, step]);

  async function handleDismiss() {
    setIsClearing(true);
    await clearAiWorking(ideaId);
    setIsClearing(false);
  }

  const fields = STEP_FIELDS[step] ?? [];
  const fieldList = fields.join(", ");

  if (showSuccess && !justCompleted) return null;

  // Stuck state: show error panel instead of spinner
  if (isStuck) {
    return (
      <div className="relative flex flex-col items-center justify-center min-h-96 gap-6">
        <div className="flex flex-col items-center gap-4 text-center max-w-sm">
          <div className="w-16 h-16 rounded-full bg-red-500/10 flex items-center justify-center">
            <svg className="w-8 h-8 text-red-400" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" />
            </svg>
          </div>
          <p className="text-base font-semibold text-text-primary">AI generation did not complete</p>
          <p className="text-sm text-text-muted">The step has been unblocked. You can try regenerating.</p>
          <button
            onClick={handleDismiss}
            disabled={isClearing}
            className={cn(
              "px-4 py-2.5 rounded-lg text-sm font-medium",
              "bg-accent text-white hover:bg-accent/90 transition-colors",
              "disabled:opacity-50 disabled:cursor-not-allowed"
            )}
          >
            {isClearing ? "Clearing…" : "Dismiss"}
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="relative flex flex-col items-center justify-center min-h-96">
      {/* Success banner */}
      {showSuccess && (
        <div
          className={cn(
            "absolute top-0 left-0 right-0 px-4 py-3 rounded-lg text-sm font-medium text-center",
            "bg-green-500 text-white"
          )}
          role="status"
        >
          Success! Our AI has started updating {fieldList}
        </div>
      )}

      {/* Spinner + message */}
      {!justCompleted && (
        <div className="flex flex-col items-center gap-6 mt-8">
          {/* Animated sparkle circle */}
          <div className="w-24 h-24 rounded-full bg-accent flex items-center justify-center animate-pulse">
            <svg
              className="w-12 h-12 text-white"
              fill="currentColor"
              viewBox="0 0 24 24"
            >
              <path d="M12 2 L13.5 9.5 L21 12 L13.5 14.5 L12 22 L10.5 14.5 L3 12 L10.5 9.5 Z" />
            </svg>
          </div>

          <p className="text-xl font-semibold text-text-primary">
            AI is working...
          </p>
          {fields.length > 0 && (
            <p className="text-sm text-text-muted text-center max-w-sm">
              Soon you will have {fieldList} updated
            </p>
          )}
        </div>
      )}
    </div>
  );
}
